function AttemptAllStructureGenerations(chunk, chunkX,chunkY,chunkWidth, generationStep, stepList, worldSeed, depthProgression, biomeSize, biomeList, world)
    --print("helo")
    --print("Attempting structure generation for chunk at "..chunkX..","..chunkY.." at step "..generationStep)
    for i = 1, #MainStructureList do
        if MainStructureList[i].spawnStep == generationStep then
            --print("Attempting to spawn structure "..MainStructureList[i].name.." at chunk "..chunkX..","..chunkY.." at step "..generationStep)
            MainStructureList[i]:attemptSpawn(chunk, chunkX,chunkY,chunkWidth, generationStep, stepList, worldSeed, depthProgression, biomeSize, biomeList, world)
        end
    end
    if generationStep == "structures" then
        if #world.mainStructureList > 0 then
            for i = 1, #world.mainStructureList do
                local structure = world.mainStructureList[i]
                local actualStructure = nil
                for i2 = 1, #MainStructureList do
                    if MainStructureList[i2].name == structure.name then
                        --print("Found structure "..structure.name.." in MainStructureList")
                        actualStructure = MainStructureList[i2]
                    end
                end
                local sChunkX, sChunkY, posInChunkX, posInChunkY = world:convertWorldPosToChunkPos(structure.x, structure.y)
                if sChunkX == round(((chunkX + (world.loopX / chunkWidth)/2) % (world.loopX / chunkWidth)) - (world.loopX / chunkWidth)/2) and sChunkY == chunkY and actualStructure ~= nil then
                    --print("Spawning structure "..structure.name.." at chunk "..chunkX..","..chunkY.." at step "..generationStep)
                    actualStructure:forceSpawn(chunkX*chunkWidth, structure.y)
                end
            end
        end
    end 
end